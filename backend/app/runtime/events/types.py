from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, Optional
from pydantic import BaseModel, Field


class RuntimeEventType(str, Enum):
    # Session lifecycle
    SESSION_CREATED = "SESSION_CREATED"
    SESSION_INITIALIZING = "SESSION_INITIALIZING"
    SESSION_STARTED = "SESSION_STARTED"
    USER_SPEECH_STARTED = "USER_SPEECH_STARTED"
    USER_TRANSCRIPT_PARTIAL = "USER_TRANSCRIPT_PARTIAL"
    USER_TRANSCRIPT_FINAL = "USER_TRANSCRIPT_FINAL"
    LLM_REQUEST_STARTED = "LLM_REQUEST_STARTED"
    LLM_RESPONSE = "LLM_RESPONSE"
    TOOL_CALL_STARTED = "TOOL_CALL_STARTED"
    TOOL_CALL_COMPLETED = "TOOL_CALL_COMPLETED"
    TTS_STARTED = "TTS_STARTED"
    TTS_COMPLETED = "TTS_COMPLETED"
    TTS_AUDIO_CHUNK = "TTS_AUDIO_CHUNK"
    ASSISTANT_RESPONSE = "ASSISTANT_RESPONSE"
    ASSISTANT_INTERRUPTED = "ASSISTANT_INTERRUPTED"
    AUDIO_SESSION_CONNECTED = "AUDIO_SESSION_CONNECTED"
    AUDIO_SESSION_DISCONNECTED = "AUDIO_SESSION_DISCONNECTED"
    AUDIO_FRAME_RECEIVED = "AUDIO_FRAME_RECEIVED"
    LLM_TOKEN = "LLM_TOKEN"
    SESSION_ENDING = "SESSION_ENDING"
    SESSION_COMPLETED = "SESSION_COMPLETED"
    SESSION_FAILED = "SESSION_FAILED"
    SESSION_ERROR = "SESSION_ERROR"

    # Telephony lifecycle (Phase 3C)
    CALL_INITIATED = "CALL_INITIATED"
    CALL_RECEIVED = "CALL_RECEIVED"
    CALL_ROUTING_STARTED = "CALL_ROUTING_STARTED"
    CALL_ROUTED = "CALL_ROUTED"
    CALL_ANSWERED = "CALL_ANSWERED"
    TELEPHONY_MEDIA_CONNECTED = "TELEPHONY_MEDIA_CONNECTED"
    TELEPHONY_MEDIA_DISCONNECTED = "TELEPHONY_MEDIA_DISCONNECTED"
    CALL_COMPLETED = "CALL_COMPLETED"
    CALL_FAILED = "CALL_FAILED"



class RuntimeEventPayload(BaseModel):
    event_id: str
    session_id: str
    agent_id: str
    agent_version_id: str
    client_id: str
    event_type: RuntimeEventType
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    payload: Dict[str, Any] = Field(default_factory=dict)
